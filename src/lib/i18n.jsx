export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem('lang') || 'th');

  useEffect(() => {
    localStorage.setItem('lang', lang);
    document.documentElement.lang = lang;
  }, [lang]);

  const t = (key) => translations[lang][key] || translations.en[key] || key;
  const toggle = () => setLang((l) => (l === 'th' ? 'en' : 'th'));

  return (
    <LanguageContext.Provider value={{ lang, setLang, toggle, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) return { lang: 'th', setLang: () => {}, toggle: () => {}, t: (k) => k };
  return ctx;
}

// Helper to pick a localized field from an entity
export function localized(item, field, lang) {
  if (!item) return '';
  const primary = item[`${field}_${lang}`];
  if (primary) return primary;
  return item[`${field}_${lang === 'th' ? 'en' : 'th'}`] || item[field] || '';
}